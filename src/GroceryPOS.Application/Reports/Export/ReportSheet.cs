namespace GroceryPOS.Application.Reports.Export;

/// <summary>How a report column's values are typed and formatted in the exported workbook.</summary>
public enum ReportColumnKind
{
    Text = 0,

    /// <summary>Whole numbers (counts): #,##0.</summary>
    Integer = 1,

    /// <summary>Quantities with up to 3 decimals (kg, lít): #,##0.###.</summary>
    Quantity = 2,

    /// <summary>VND amounts: #,##0 ₫.</summary>
    Money = 3,

    /// <summary>Percent given as a number of percent (12.5 = 12,5 %); writers convert to a fraction.</summary>
    Percent = 4,

    /// <summary><see cref="DateOnly"/> values: dd/MM/yyyy.</summary>
    Date = 5,
}

public sealed record ReportColumn(string Header, ReportColumnKind Kind, double Width = 0);

/// <summary>
/// A format-neutral table of report figures – one worksheet of an export. Built by <see cref="ReportSheets"/>
/// from the report DTOs and written by an <see cref="Abstractions.IReportWorkbookWriter"/>, so the document
/// library stays in Infrastructure and the layout rules stay testable.
/// </summary>
public sealed record ReportSheet
{
    public const int MaxNameLength = 31;
    private static readonly char[] InvalidNameChars = ['[', ']', ':', '*', '?', '/', '\\'];

    public ReportSheet(
        string name,
        string title,
        IReadOnlyList<string> subtitles,
        IReadOnlyList<ReportColumn> columns,
        IReadOnlyList<IReadOnlyList<object?>> rows,
        IReadOnlyList<object?>? totals = null)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(name);
        ArgumentException.ThrowIfNullOrWhiteSpace(title);
        ArgumentNullException.ThrowIfNull(subtitles);
        ArgumentNullException.ThrowIfNull(columns);
        ArgumentNullException.ThrowIfNull(rows);

        if (name.Length > MaxNameLength || name.IndexOfAny(InvalidNameChars) >= 0)
        {
            throw new ArgumentException($"Tên trang tính \"{name}\" không hợp lệ.", nameof(name));
        }

        if (columns.Count == 0)
        {
            throw new ArgumentException("Báo cáo phải có ít nhất một cột.", nameof(columns));
        }

        foreach (var row in rows)
        {
            if (row.Count != columns.Count)
            {
                throw new ArgumentException($"Mỗi dòng phải có đúng {columns.Count} ô.", nameof(rows));
            }
        }

        if (totals is not null && totals.Count != columns.Count)
        {
            throw new ArgumentException($"Dòng tổng phải có đúng {columns.Count} ô.", nameof(totals));
        }

        Name = name;
        Title = title;
        Subtitles = subtitles;
        Columns = columns;
        Rows = rows;
        Totals = totals;
    }

    /// <summary>Worksheet tab name (≤ 31 characters, no [ ] : * ? / \).</summary>
    public string Name { get; }

    public string Title { get; }

    /// <summary>Lines under the title: store, period, generated by/at.</summary>
    public IReadOnlyList<string> Subtitles { get; }

    public IReadOnlyList<ReportColumn> Columns { get; }

    public IReadOnlyList<IReadOnlyList<object?>> Rows { get; }

    /// <summary>Optional bold "Tổng cộng" row.</summary>
    public IReadOnlyList<object?>? Totals { get; }
}

/// <summary>An exported report file ready to save.</summary>
public sealed record ReportFile(string FileName, byte[] Content);
